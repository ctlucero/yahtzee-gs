"""Regenerates src/screen/dice_shapes.inc (from the regions the original
program builds, by running it in the emulator) and src/screen/gs8_font.inc.
Usage: YAHTZEE_BIN=path/to/YAHTZEE python3 tools/export_assets.py"""
from qdemu import Toolbox
from emu import SEG2
tb = Toolbox(); tb.call(0x8B11)
rg = lambda a: tb.regions.get(tb.r32(SEG2 + a), set())
edge = rg(0x131)
out = ['// Dice shapes, generated from the regions the original program builds',
       '// (P806D, P8451). One 36x30 map per face value 0..6, in control-local',
       "// coordinates. 'S' pip shadow, 'H' pip highlight, 'b' die body, 'E' edge,",
       "// '.' untouched. Generated by tools/export_assets.py.",
       'static const char* const kDiceShapes[7][30] = {']
for v in range(7):
    S, Hh, B = rg(0xDD + 4 * v), rg(0xF9 + 4 * v), rg(0x115 + 4 * v)
    out.append('  {')
    for y in range(30):
        row = ''.join('E' if (x, y) in edge else 'b' if (x, y) in B else 'H' if (x, y) in Hh
                      else 'S' if (x, y) in S else '.' for x in range(36))
        out.append(f'    "{row}",')
    out.append('  },')
out.append('};')
open('src/screen/dice_shapes.inc', 'w').write('\n'.join(out) + '\n')
src = open('assets/fonts/gs8.txt').read()
open('src/screen/gs8_font.inc', 'w').write(
    '// Generated from assets/fonts/gs8.txt by tools/export_assets.py\nR"FONT(' + src + ')FONT"\n')
