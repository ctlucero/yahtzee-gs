# Generate test vectors by running the ORIGINAL 65816 code in the emulator.
import itertools, random
from emu import CPU, SEG2
from oracle import plan as orig_plan
cpu=CPU(); base=bytes(cpu.mem)
out=open('tests/data/original_vectors.txt','w')
out.write('# Generated by running the original YAHTZEE 65816 code (P48B5, P4B2B) in an emulator.\n')
out.write('# P <dice> <category> <rerollsLeft> <value> <reroll flags by sorted position>\n')
out.write('# C <dice> <mode> <open mask, bit c-1> <13 scores> <13 plan values> <chosen category>\n')
for d in itertools.combinations_with_replacement(range(1,7),5):
    for roll in (0,1):
        for c in range(1,14):
            v,f=orig_plan(d,c,roll)
            out.write(f"P {''.join(map(str,d))} {c} {roll} {v} {''.join(map(str,f))}\n")
random.seed(1988)
for t in range(2500):
    d=sorted(random.randint(1,6) for _ in range(5)); random.shuffle(d)
    roll=random.choice([0,1]); player=random.randint(1,4)
    k=random.randint(1,13)
    opened={c:False for c in range(1,14)}
    for c in random.sample(range(1,14),k): opened[c]=True
    scores={c:(0 if opened[c] else (c*random.randint(0,5) if c<=6 else random.choice([0,5,12,17,22,25,30,40,50]))) for c in range(1,14)}
    sd=sorted(d)
    table={c:orig_plan(sd,c,roll)[0] for c in range(1,14)}
    for mode in (0,1):
        cpu.mem[:]=base; cpu.reset()
        for i,v in enumerate(sd): cpu.ww(SEG2+0x4F7+4*i,v); cpu.ww(SEG2+0x4F9+4*i,i+1)
        cpu.ww(SEG2+0x0A,roll); cpu.ww(SEG2+0x14,player)
        rec=SEG2+0x3F3+(player-1)*65
        for c in range(1,14):
            cpu.wb(rec+0x1A+c-1,1 if opened[c] else 0); cpu.ww(rec+0x27+2*(c-1),scores[c]); cpu.ww(SEG2+0x16+(c-1)*7,table[c])
        cpu.call(0x4B2B,[0,mode]); got=cpu.pull16()
        mask=sum(1<<(c-1) for c in range(1,14) if opened[c])
        out.write(f"C {''.join(map(str,d))} {mode} {mask} {' '.join(str(scores[c]) for c in range(1,14))} {' '.join(str(table[c]) for c in range(1,14))} {got}\n")
out.close()
